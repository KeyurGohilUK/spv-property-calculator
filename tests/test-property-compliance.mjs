import assert from 'node:assert/strict';
import {PROPERTY_REQUIREMENTS,daysUntil,assessRequirement,buildPropertyCompliance} from '../src/features/property-compliance/compliance-rules.js';
const today='2026-11-20';
const req=Object.fromEntries(PROPERTY_REQUIREMENTS.map(r=>[r.id,r]));
const assess=(id,record={},property={})=>assessRequirement(req[id],record,property,today);
assert.equal(daysUntil('2026-11-21',today),1);
assert.equal(daysUntil('2026-02-30',today),null);
assert.equal(assess('epc',{confirmed:true,expiryDate:'2031-11-20'}).status,'compliant');
assert.equal(assess('gas',{confirmed:true,expiryDate:'2026-11-10'}).status,'overdue');
assert.equal(assess('gas',{}, {hasGas:false}).status,'not-applicable');
assert.equal(assess('deposit',{}, {hasDeposit:false}).status,'not-applicable');
assert.equal(assess('epc',{confirmed:false,expiryDate:'2031-11-20'}).status,'verification-required');
assert.equal(assess('epc',{confirmed:true,hasExpiry:true}).status,'verification-required');
assert.equal(assess('epc',{confirmed:true,expiryDate:'2031-11-20',seriousHazard:true}).status,'critical');
assert.equal(assess('epc',{confirmed:true,expiryDate:'2031-11-20',remedialActionOpen:true}).status,'action-required');
const data=buildPropertyCompliance({today,records:{gas:{confirmed:true,expiryDate:'2026-11-10'},epc:{confirmed:true,expiryDate:'2031-11-20'}}});
assert.equal(data.items[0].id,'gas');
assert.equal(data.items.at(-1).id,'epc');
assert.equal(data.counts.compliant,1);
assert.ok(buildPropertyCompliance({today,group:'safety'}).items.every(item=>item.group==='safety'));
assert.throws(()=>buildPropertyCompliance({today:'bad'}),/today/);
console.log('Property compliance rules tests passed');
