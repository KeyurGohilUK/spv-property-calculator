import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { buildCompanyCompliance, companyHouseDeadlines } from '../src/features/company/compliance-rules.js';
const incoming = { accounts: { next_accounts: { due_on: '2027-04-30' }, next_due: '2027-05-01' }, confirmation_statement: { next_due: '2026-11-16' } };
assert.deepEqual(companyHouseDeadlines(incoming), { 'annual-accounts': '2027-04-30', 'confirmation-statement': '2026-11-16' });
const rules = buildCompanyCompliance({ company: incoming, today: '2026-11-02' });
assert.equal(rules.find(x => x.id === 'confirmation-statement').status, 'due-soon');
assert.equal(rules.find(x => x.id === 'annual-accounts').dueDate, '2027-04-30');
assert.equal(rules.find(x => x.id === 'corporation-tax-return').dueDate, null);
const source = readFileSync(new URL('../supabase/functions/company-house-lookup/index.ts', import.meta.url), 'utf8');
const cloud = readFileSync(new URL('../cloud.js', import.meta.url), 'utf8');
const ui = readFileSync(new URL('../src/features/company/company.js', import.meta.url), 'utf8');
const config = readFileSync(new URL('../supabase/config.toml', import.meta.url), 'utf8');
assert.match(source, /COMPANIES_HOUSE_API_KEY/);
assert.match(source, /getUser\(jwt\)/);
assert.match(source, /workspace_members/);
assert.match(source, /next_accounts\?\.due_on/);
assert.doesNotMatch(ui, /COMPANIES_HOUSE_API_KEY/);
assert.match(cloud, /functions\.invoke\('company-house-lookup'/);
assert.match(ui, /refreshCompanyHouseDeadlines\(\)/);
assert.match(ui, /companyHouseData/);
assert.match(config, /\[functions\.company-house-lookup\]/);
console.log('Companies House deadline mapping and authenticated proxy checks passed.');
