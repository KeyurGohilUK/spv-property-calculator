import fs from 'node:fs'; import vm from 'node:vm';
const source=fs.readFileSync(new URL('./cloud.js',import.meta.url),'utf8');
const window={SPV_SUPABASE_CONFIG:{url:'https://YOUR_PROJECT_REF.supabase.co',publishableKey:'sb_publishable_REPLACE_ME'}};
vm.runInContext(source,vm.createContext({window,document:{},console,setTimeout,clearTimeout}));
const merge=window.SPVCloud.mergePropertySets;
const local=[{id:'a',title:'Local newer',updatedAt:'2026-08-12T10:00:00Z',deletedAt:null},{id:'b',title:'Local archived',updatedAt:'2026-08-12T11:00:00Z',deletedAt:'2026-08-12T11:00:00Z'}];
const cloud=[{id:'a',title:'Cloud older',updatedAt:'2026-08-12T08:00:00Z',deletedAt:null},{id:'c',title:'Cloud archived',updatedAt:'2026-08-12T12:00:00Z',deletedAt:'2026-08-12T12:00:00Z'}];
const result=merge(local,cloud), byId=new Map(result.merged.map(x=>[x.id,x]));
if(byId.get('a')?.title!=='Local newer') throw new Error('newer local should win');
if(!byId.get('b')?.deletedAt||!byId.get('c')?.deletedAt) throw new Error('archived rows must remain in merge');
if(!result.upload.some(x=>x.id==='a')||!result.upload.some(x=>x.id==='b')) throw new Error('expected uploads missing');
if(!source.includes("onConflict: 'id'")) throw new Error('shared id upsert missing');
if(!source.includes('deleted_at: record.deletedAt || null')) throw new Error('deleted_at persistence missing');
if(!source.includes('archivedLegacyIds')) throw new Error('legacy conversion missing');
if(source.includes('.delete()')) throw new Error('hard delete still present');
if(source.includes('deleteProperty,')) throw new Error('hard delete API exposed');
console.log('Soft-delete cloud merge tests passed.');
